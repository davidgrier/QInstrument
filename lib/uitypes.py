'''Generate typing declarations for widgets loaded from Qt Designer files.

``uic.loadUi`` attaches every named child widget and layout of a ``.ui``
file to the widget at run time, so a static type checker cannot see
them.  This module reads a ``.ui`` file and writes ``<name>_ui.py``
next to it: a class that only *annotates* those attributes.  A widget
class lists the generated class among its bases, and the checker then
knows every child; at run time the class adds nothing.

Regenerate after editing a ``.ui`` file::

    python -m QInstrument.lib.uitypes

``--check`` regenerates nothing and exits with status 1 if a generated
file is missing or stale; the test suite does the same.
'''

from pathlib import Path
import argparse
import sys
import xml.etree.ElementTree as ET

__all__ = ['generate', 'ui_files', 'main']

# Hand-annotated: the widget delegates methods that share names with children.
SKIP = frozenset({'QRotaryEncoderSpinBox.ui'})

HEADER = '# Generated by QInstrument.lib.uitypes from {ui}. Do not edit.\n'


def _custom_widgets(root: ET.Element) -> dict[str, str]:
    '''Map custom widget class names to the module that defines them.'''
    custom = {}
    for node in root.iterfind('./customwidgets/customwidget'):
        name = node.findtext('class')
        header = node.findtext('header')
        if name and header:
            custom[name] = header.removesuffix('.h')
    return custom


def generate(ui: Path) -> str:
    '''Return the source of the typing module for a ``.ui`` file.

    Parameters
    ----------
    ui : pathlib.Path
        Qt Designer file.

    Returns
    -------
    str
        Python source declaring the named children as annotations.
    '''
    root = ET.parse(ui).getroot()
    custom = _custom_widgets(root)
    top = root.find('widget')
    if top is None:
        raise ValueError(f'{ui}: no top-level widget')
    members: dict[str, str] = {}
    for node in top.iter():
        if node is top or node.tag not in ('widget', 'layout'):
            continue
        name, cls = node.get('name'), node.get('class')
        if name and cls:
            members[name] = cls
    lines = [HEADER.format(ui=ui.name),
             'from qtpy import QtWidgets', '']
    lines += [f'from {custom[c]} import {c}'
              for c in sorted(set(members.values()) & set(custom))]
    cname = f'Ui{top.get("name", ui.stem)}'
    lines += ['', '', f'class {cname}:', f"    '''Children of {ui.name}.'''",
              '']
    for name, cls in members.items():
        kind = cls if cls in custom else f'QtWidgets.{cls}'
        lines.append(f'    {name}: {kind}')
    if not members:
        lines.append('    pass')
    return '\n'.join(lines) + '\n'


def ui_files(base: Path) -> list[Path]:
    '''Return the ``.ui`` files below *base*, skipping hidden folders.'''
    return sorted(p for p in base.rglob('*.ui')
                  if p.name not in SKIP and not any(part.startswith('.')
                             for part in p.relative_to(base).parts))


def target(ui: Path) -> Path:
    '''Return the path of the generated module for a ``.ui`` file.'''
    return ui.with_name(f'{ui.stem}_ui.py')


def main(argv: list[str] | None = None) -> int:
    '''Write (or with ``--check``, verify) the typing modules.'''
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('base', nargs='?', type=Path,
                        default=Path(__file__).parents[1],
                        help='directory to search for .ui files')
    parser.add_argument('--check', action='store_true',
                        help='report stale files instead of writing')
    args = parser.parse_args(argv)
    stale = 0
    for ui in ui_files(args.base):
        out, source = target(ui), generate(ui)
        if out.exists() and out.read_text() == source:
            continue
        if args.check:
            print(f'stale: {out}')
            stale += 1
        else:
            out.write_text(source)
            print(f'wrote: {out}')
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
